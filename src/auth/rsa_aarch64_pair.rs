//! Paired CRT exponentiation for Apple AArch64: the p and q exponentiations of an RSA private
//! operation run together, one in each 64-bit lane of the vector unit.
//!
//! A residue modulo either prime has `D` radix-2^28 digits. Digit `j` of a pair is the eight-byte
//! word `p_j | q_j << 32`, stored twice in a 16-byte slot, so one `LDR Q` loads a multiplier that
//! both `UMLAL` (low halves) and `UMLAL2` (high halves) can use. One almost-Montgomery
//! multiplication (AMM) computes `a·b·R⁻¹` modulo each prime for `R = 2^(28·D)`; inputs below `2·m`
//! give an output below `2·m`, because `4·m < R`. Products of 28-bit digits fit 56 bits, so the
//! 64-bit column sums, at most `2·D + 1 < 256` products each, cannot overflow, and no carry moves
//! until a column is complete. `scripts/asm/rsa_pair_aarch64.py` documents the kernel schedule and
//! generates both kernels; `scripts/asm/rsa_pair.py simulate` checks them against Python integers.
//!
//! The engine is selected on Apple cores only. Their vector unit issues four `UMLAL` per cycle
//! against two scalar `MUL`/`UMULH`, which pays for the radix-2^28 representation's 1.31 times
//! more digit products than radix 2^64. Neoverse V2 (Graviton4) issues two `UMLAL` per cycle and
//! one 64-bit product per cycle, and its scalar and vector multipliers barely overlap, so there
//! the scalar kernels stay faster.
//!
//! Loop counts, branches and addresses depend only on the public digit count. Secret digits reach
//! only multiplications, additions, shifts, masks, conditional increments and stores; the
//! exponents select table entries through lane masks. `rsa.rs` owns validation, dispatch, the
//! Montgomery constant and the portable fallback, which computes the same values.

// Diagnostic builds compile the kernels on every AArch64 target for the constant-time harnesses;
// only Apple production builds dispatch the exponentiation.
#![cfg_attr(
  not(all(target_vendor = "apple", not(feature = "portable-only"))),
  allow(
    dead_code,
    unused_imports,
    reason = "only Apple production builds dispatch the exponentiation"
  )
)]

use super::{private_select_window_power_neon, subtract_modulus_if_needed};

const MASK28: u64 = (1 << 28) - 1;
const WINDOW_ENTRIES: usize = 16;
/// Digits per kernel block: the kernels hold eight digits of an operand in registers.
const BLOCK_DIGITS: usize = 8;
/// `u64` words of the kernels' parameter block: the eight multiplier pairs of the current block,
/// `n'·2^36` and `n_0 + n_1·2^28` per lane, the output pointer, and three shape words.
const PARAM_WORDS: usize = 16;
const PARAM_K: usize = 8;
const PARAM_N01: usize = 10;
const PARAM_OUT: usize = 12;
const PARAM_BLOCKS: usize = 13;
const PARAM_BACK: usize = 14;
const PARAM_STRIDE: usize = 15;

/// Digit count `D` for primes of `limbs` 64-bit limbs, or `None` without a kernel shape.
///
/// `28·D >= 64·limbs + 2`, so `4·m < R`, and `D` is a multiple of eight with at least three
/// blocks.
#[inline]
pub(super) fn shape(limbs: usize) -> Option<usize> {
  match limbs {
    16 => Some(40),
    24 => Some(56),
    32 => Some(80),
    _ => None,
  }
}

/// `u64` workspace words for `digits`-digit pairs: the modulus pair, the column buffer, the
/// parameter block, the window table, three working pairs, and one word of 16-byte alignment.
fn pair_workspace_words(digits: usize) -> usize {
  let pair = digits.strict_mul(2);
  pair
    .strict_mul(1 + 2 + WINDOW_ENTRIES + 3)
    .strict_add(PARAM_WORDS)
    .strict_add(1)
}

/// `u64` workspace words for the widest kernel prime of at most `max_limbs` limbs, or zero.
///
/// Private scratch is sized by the public modulus width, about twice each CRT prime's.
#[inline]
pub(super) fn max_workspace_words(max_limbs: usize) -> usize {
  [32usize, 24, 16]
    .into_iter()
    .find(|&limbs| limbs <= max_limbs)
    .map_or(0, workspace_words)
}

/// `u64` workspace words the CRT pair needs for `limbs`-limb primes, or zero without a shape.
#[inline]
pub(super) fn workspace_words(limbs: usize) -> usize {
  shape(limbs).map_or(0, pair_workspace_words)
}

/// One prime's exponentiation operands.
pub(super) struct Operands<'a> {
  /// Fully reduced result, little-endian 64-bit limbs.
  pub(super) out: &'a mut [u64],
  /// Base below `m`.
  pub(super) base: &'a [u64],
  /// Big-endian exponent bytes, most significant first.
  pub(super) exponent: &'a [u8],
  /// Odd prime modulus.
  pub(super) m: &'a [u64],
  /// `R² mod m` for `R = 2^(28·digits)`, fully reduced.
  pub(super) r2: &'a [u64],
  /// `-m⁻¹ mod 2^64`.
  pub(super) n0: u64,
}

/// Compute both CRT exponentiations, `base^exponent mod m` for each prime, in the two lanes.
///
/// Both primes have the same limb count, `digits` is `shape` of it, both exponents have the same
/// length, and `workspace` holds at least `workspace_words` of the limb count.
pub(super) fn exponentiate_pair(operands: [Operands<'_>; 2], digits: usize, workspace: &mut [u64]) {
  let [p, q] = operands;
  let words = digits.strict_mul(2);
  assert!(
    digits.is_multiple_of(BLOCK_DIGITS)
      && digits >= BLOCK_DIGITS.strict_mul(3)
      && p.m.len() == q.m.len()
      && digits.strict_mul(28) >= p.m.len().strict_mul(64).strict_add(2)
      && p.exponent.len() == q.exponent.len()
      && workspace.len() >= pair_workspace_words(digits)
  );
  // Start at a 16-byte boundary: the kernels load and store 16-byte slots.
  let skip = workspace.as_ptr().addr().strict_div(8) & 1;
  let workspace = &mut workspace[skip..];
  let (n, rest) = workspace.split_at_mut(words);
  let (t, rest) = rest.split_at_mut(words.strict_mul(2));
  let (params, rest) = rest.split_at_mut(PARAM_WORDS);
  let (table, rest) = rest.split_at_mut(words.strict_mul(WINDOW_ENTRIES));
  let (acc, rest) = rest.split_at_mut(words);
  let (selected, rest) = rest.split_at_mut(words);
  let one = &mut rest[..words];

  to_pair(p.m, q.m, n);
  for (lane, (m, n0)) in [(p.m, p.n0), (q.m, q.n0)].into_iter().enumerate() {
    // `-m⁻¹ mod 2^28` in the top 28 bits: `x·K mod 2^64` is `((x·n') mod 2^28)·2^36`.
    params[PARAM_K.strict_add(lane)] = (n0 & MASK28) << 36;
    params[PARAM_N01.strict_add(lane)] = digit(m, 0) | (digit(m, 1) << 28);
  }
  params[PARAM_BLOCKS] = (digits / BLOCK_DIGITS) as u64;
  params[PARAM_BACK] = (digits.strict_sub(1).strict_mul(16)) as u64;
  params[PARAM_STRIDE] = (digits.strict_mul(16)) as u64;
  let mut engine = Engine { n, t, params };

  // table[k] = base^k·R (almost reduced), from R² and the AMM of one with R².
  let (entry0, entries) = table.split_at_mut(words);
  let (entry1, entries) = entries.split_at_mut(words);
  to_pair(p.r2, q.r2, selected);
  to_pair(p.base, q.base, acc);
  engine.mul(entry1, acc, selected);
  set_one(one);
  engine.mul(entry0, one, selected);
  let mut previous: &[u64] = entry1;
  for entry in entries.chunks_exact_mut(words) {
    engine.mul(entry, previous, entry1);
    previous = entry;
  }
  acc.copy_from_slice(entry0);

  // Fixed four-bit windows over every exponent byte, most significant first.
  for (&byte_p, &byte_q) in p.exponent.iter().zip(q.exponent) {
    for shift in [4u32, 0] {
      for _ in 0..4 {
        engine.square(acc);
      }
      let windows = u64::from((byte_p >> shift) & 0x0f) | (u64::from((byte_q >> shift) & 0x0f) << 32);
      // SAFETY: `selected` has `words` writable limbs and `table` holds sixteen entries of `words`
      // limbs, so the reads of `words` limbs at `words·i` for i in 0..16 stay inside it; `words` is
      // a nonzero multiple of four.
      unsafe {
        private_select_window_power_neon(selected.as_mut_ptr(), table.as_ptr(), words, words / 4, windows);
      }
      engine.mul_in_place(acc, selected);
    }
  }

  // acc·1·R⁻¹ is at most m; one conditional subtraction reduces it fully.
  engine.mul_in_place(acc, one);
  for (lane, operands) in [p, q].into_iter().enumerate() {
    from_pair(acc, lane, operands.out);
    subtract_modulus_if_needed(operands.out, operands.m, 0);
  }
}

/// Digit `j` of little-endian limbs: bits `28·j..28·j + 28`, zero beyond the limbs.
#[inline]
fn digit(limbs: &[u64], j: usize) -> u64 {
  let bit = j.strict_mul(28);
  let (index, shift) = (bit / 64, bit % 64);
  let low = limbs.get(index).map_or(0, |&limb| limb >> shift);
  // The digit crosses into the next limb when its 28 bits pass bit 63.
  let high = if shift > 36 {
    limbs
      .get(index.strict_add(1))
      .map_or(0, |&limb| limb << 64usize.strict_sub(shift))
  } else {
    0
  };
  (low | high) & MASK28
}

/// Write `p` and `q`, little-endian limbs below `2^(28·D)`, as the replicated pair `out`.
fn to_pair(p: &[u64], q: &[u64], out: &mut [u64]) {
  for (j, slot) in out.as_chunks_mut::<2>().0.iter_mut().enumerate() {
    let pair = digit(p, j) | (digit(q, j) << 32);
    slot[0] = pair;
    slot[1] = pair;
  }
}

/// The replicated pair whose lanes both hold one.
fn set_one(out: &mut [u64]) {
  out.fill(0);
  out[0] = 1 | (1 << 32);
  out[1] = out[0];
}

/// Join lane `lane` of the replicated pair `pair`, whose digits are canonical and whose value fits
/// `out`, into little-endian limbs.
fn from_pair(pair: &[u64], lane: usize, out: &mut [u64]) {
  out.fill(0);
  for (j, slot) in pair.as_chunks::<2>().0.iter().enumerate() {
    let value = (slot[0] >> lane.strict_mul(32)) & MASK28;
    let bit = j.strict_mul(28);
    let (index, shift) = (bit / 64, bit % 64);
    if let Some(limb) = out.get_mut(index) {
      *limb |= value << shift;
    }
    if shift > 36
      && let Some(limb) = out.get_mut(index.strict_add(1))
    {
      *limb |= value >> 64usize.strict_sub(shift);
    }
  }
}

/// The modulus pair, column buffer and parameter block one exponentiation's kernels share.
struct Engine<'a> {
  n: &'a [u64],
  t: &'a mut [u64],
  params: &'a mut [u64],
}

impl Engine<'_> {
  /// `out = a·b·R⁻¹` in each lane, for replicated pairs below `2·m`.
  fn mul(&mut self, out: &mut [u64], a: &[u64], b: &[u64]) {
    let words = self.n.len();
    assert!(out.len() == words && a.len() == words && b.len() == words);
    // SAFETY: Each slice holds the kernel's `words` limbs, and `out` does not overlap `a` or `b`.
    unsafe { self.mul_raw(out.as_mut_ptr(), a.as_ptr(), b.as_ptr()) };
  }

  /// `value = value·b·R⁻¹` in each lane.
  fn mul_in_place(&mut self, value: &mut [u64], b: &[u64]) {
    let words = self.n.len();
    assert!(value.len() == words && b.len() == words);
    let value = value.as_mut_ptr();
    // SAFETY: Both slices hold `words` limbs. The kernel reads its operands only before the final
    // pass, which alone writes the output, so the output may be the first operand.
    unsafe { self.mul_raw(value, value, b.as_ptr()) };
  }

  /// `value = value²·R⁻¹` in each lane.
  fn square(&mut self, value: &mut [u64]) {
    let words = self.n.len();
    assert!(value.len() == words && self.t.len() >= words.strict_mul(2));
    let value = value.as_mut_ptr();
    // The kernel reads the output pointer from the parameter block, so its provenance is exposed.
    self.params[PARAM_OUT] = value.expose_provenance() as u64;
    // SAFETY: `value`, `n` and `t` hold the `words`, `words` and `2·words` limbs the kernel reads
    // and writes, `params` holds its sixteen words, and the output pointer in `params` is `value`,
    // which the kernel writes only in its final pass, after its last read of the operand.
    unsafe { square_kernel(self.t.as_mut_ptr(), self.n.as_ptr(), value, self.params.as_mut_ptr()) };
  }

  /// # Safety
  ///
  /// `out`, `a` and `b` must each be valid for `n.len()` limbs; `out` may equal `a` or `b` but
  /// must not overlap them otherwise.
  unsafe fn mul_raw(&mut self, out: *mut u64, a: *const u64, b: *const u64) {
    assert!(self.t.len() >= self.n.len().strict_mul(2));
    // The kernel reads the output pointer from the parameter block, so its provenance is exposed.
    self.params[PARAM_OUT] = out.expose_provenance() as u64;
    // SAFETY: The caller guarantees the operand and output limbs; `n`, `t` and `params` hold the
    // `words`, `2·words` and sixteen words the kernel reads and writes.
    unsafe { mul_kernel(self.t.as_mut_ptr(), self.n.as_ptr(), a, b, self.params.as_mut_ptr()) };
  }
}

