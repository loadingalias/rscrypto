//! x86-64 kernels for P-384 ECDH field and point arithmetic.
//!
//! Each kernel computes the same canonical result as its portable authority
//! in `p384_portable.rs`: `montgomery_mul`, `montgomery_square`,
//! `Uint::add_mod`, `Uint::sub_mod`, the addition chains behind
//! `FieldElement::{triple, times4, times8}`, and the point operation
//! `Jacobian::double_formula`. The point block fuses the whole formula so that
//! field values stay in one frame instead of passing through Rust between
//! kernels. Multiplication and squaring use BMI2
//! `MULX` with
//! the ADX `ADCX`/`ADOX` pair, which lets each product row run its low-half
//! and high-half carry chains through CF and OF independently. Callers select
//! it only after `platform::caps()` reports BMI2 and ADX; other CPUs keep the
//! portable multiplication. Addition and subtraction need only the x86-64
//! baseline.
//!
//! Rust inline assembly leaves 13 general-purpose registers on x86-64, so the
//! multiplication keeps a rotating seven-limb row window in registers, stores
//! finished product limbs to a stack buffer, and reads the second operand
//! and the reduction constants from memory. The reduction follows
//! `p384_aarch64.rs`: with `q = t0 + (t0 << 32)`, each step uses
//! `t + q * p = t - q * c + q * 2^384`, where `c = 2^384 - p`, and defers the
//! borrow out of the fourth window limb to the next step.
//!
//! The kernels contain no branches and address memory only at fixed offsets
//! from their operands and constants. Instruction timing is a target
//! property; this source shape is not a constant-time claim by itself.
//!
//! SECURITY: No block uses `options(pure)`, which would let LLVM skip or sink
//! a kernel into a branch on the mask that later selects its result.

/// `[2^64 - 2^32 + 1, 2^32 - 1]`, the low limbs of `c = 2^384 - p`.
static REDUCTION_CONSTANTS: [u64; 2] = [0xffff_ffff_0000_0001, 0x0000_0000_ffff_ffff];
/// The field modulus `p`.
static MODULUS: [u64; 6] = super::FIELD_MODULUS.0;

