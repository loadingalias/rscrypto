//! AArch64 kernels for P-384 ECDH field arithmetic and comb selection.
//!
//! Each kernel computes the same canonical result as its portable authority
//! in `p384_portable.rs`: `montgomery_mul`, `montgomery_square`,
//! `Uint::add_mod`, `Uint::sub_mod`, the addition chains behind
//! `FieldElement::{triple, times4, times8}`, and the fixed-base comb scan. The field
//! kernels exist because LLVM lowers the portable 6x64 carry chains through
//! repeated flag materialization; here `MUL` and `UMULH` feed `ADDS`/`ADCS`
//! chains directly, since neither multiply instruction reads or writes NZCV.
//! On Apple cores the NZCV-writing and -reading instructions issue on fewer
//! ports than plain integer ones, so the kernels move work to the multiply
//! units and non-flag ALU instructions where the arithmetic allows.
//!
//! Multiplication and squaring form the full 768-bit product, reduce its low
//! half in place, and add the high half. With `-p^-1 mod 2^64 = 2^32 + 1`,
//! each reduction step replaces the low limb `t0` by `q = t0 + (t0 << 32)`
//! and uses `t + q * p = t - q * c + q * 2^384`, where `c = 2^384 - p =
//! 2^128 + 2^96 - 2^32 + 1`. The low limb of `q * c` equals `t0`, so it
//! cancels without a borrow; the next three limbs come from one `UMULH` by
//! `c0 = 2^64 - 2^32 + 1` and a `MUL`/`UMULH` pair by `c1 = 2^32 - 1`. The
//! register that held `t0` then holds `q` as the new top limb. A step's
//! borrow out of its fourth limb is kept in a register and subtracted at the
//! same position in the next step, where that limb has become the fourth
//! limb again; only the last step propagates its borrow through the window.
//!
//! The field kernels contain no branches, access no memory, and finish with a
//! `CSEL` or masked correction. The comb scan branches only on its public
//! loop counter and loads every table entry. Instruction timing is a target
//! property; this source shape is not a constant-time claim by itself.
//!
//! SECURITY: No block uses `options(pure)`. A pure block lets LLVM skip or
//! sink the kernel into a branch on the mask that later selects its result;
//! this made the signed-window negation branch on the digit sign.

